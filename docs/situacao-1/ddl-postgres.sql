BEGIN;

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      VARCHAR(128) NOT NULL,
    last_login    TIMESTAMPTZ NULL,
    is_superuser  BOOLEAN      NOT NULL,
    is_staff      BOOLEAN      NOT NULL,
    is_active     BOOLEAN      NOT NULL,
    date_joined   TIMESTAMPTZ  NOT NULL,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    telefone      VARCHAR(20)  NOT NULL,
    perfil        VARCHAR(10)  NOT NULL DEFAULT 'CLIENTE',
    criado_em     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('CLIENTE', 'ADMIN'))
);

CREATE TABLE endereco (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    apelido      VARCHAR(40)  NOT NULL,
    logradouro   VARCHAR(150) NOT NULL,
    numero       VARCHAR(10)  NOT NULL,
    complemento  VARCHAR(60)  NOT NULL,
    bairro       VARCHAR(80)  NOT NULL,
    cidade       VARCHAR(80)  NOT NULL,
    cep          VARCHAR(9)   NOT NULL,
    principal    BOOLEAN      NOT NULL
);
CREATE INDEX endereco_usuario_id_idx ON endereco (usuario_id);

CREATE TABLE categoria (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(60) NOT NULL UNIQUE,
    slug   VARCHAR(70) NOT NULL UNIQUE,
    ativa  BOOLEAN     NOT NULL,
    ordem  SMALLINT    NOT NULL CHECK (ordem >= 0)
);

CREATE TABLE produto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id   BIGINT        NOT NULL REFERENCES categoria (id) DEFERRABLE INITIALLY DEFERRED, -- PROTECT (na aplicação)
    nome           VARCHAR(80)   NOT NULL,
    descricao      TEXT          NOT NULL,
    ingredientes   VARCHAR(300)  NOT NULL,
    preco          NUMERIC(8,2)  NOT NULL,
    estoque        INTEGER       NOT NULL CHECK (estoque >= 0),
    imagem         VARCHAR(120)  NOT NULL,
    ativo          BOOLEAN       NOT NULL,
    destaque       BOOLEAN       NOT NULL,
    criado_em      TIMESTAMPTZ   NOT NULL,
    atualizado_em  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_produto_preco_positivo        CHECK (preco > 0),
    CONSTRAINT ck_produto_estoque_nao_negativo  CHECK (estoque >= 0),
    CONSTRAINT uq_produto_categoria_nome        UNIQUE (categoria_id, nome)
);
CREATE INDEX produto_categoria_id_idx ON produto (categoria_id);

CREATE TABLE zona_entrega (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bairro  VARCHAR(80)  NOT NULL UNIQUE,
    taxa    NUMERIC(6,2) NOT NULL,
    ativa   BOOLEAN      NOT NULL,
    CONSTRAINT ck_zona_taxa_nao_negativa CHECK (taxa >= 0)
);

CREATE TABLE pedido (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT        NOT NULL REFERENCES usuario (id) DEFERRABLE INITIALLY DEFERRED, -- PROTECT
    tipo_entrega      VARCHAR(10)   NOT NULL,
    endereco_entrega  VARCHAR(300)  NOT NULL,
    bairro            VARCHAR(80)   NOT NULL,
    status            VARCHAR(20)   NOT NULL DEFAULT 'RECEBIDO',
    subtotal          NUMERIC(10,2) NOT NULL,
    taxa_entrega      NUMERIC(6,2)  NOT NULL,
    total             NUMERIC(10,2) NOT NULL,
    observacao        VARCHAR(300)  NOT NULL,
    criado_em         TIMESTAMPTZ   NOT NULL,
    atualizado_em     TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_pedido_total_nao_negativo CHECK (total >= 0),
    CONSTRAINT ck_pedido_retirada_sem_taxa  CHECK ((tipo_entrega = 'RETIRADA' AND taxa_entrega = 0) OR tipo_entrega = 'ENTREGA')
);
CREATE INDEX pedido_usuario_id_idx ON pedido (usuario_id);

CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT       NOT NULL REFERENCES pedido (id)  ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    produto_id      BIGINT       NOT NULL REFERENCES produto (id) DEFERRABLE INITIALLY DEFERRED, -- PROTECT
    nome_produto    VARCHAR(80)  NOT NULL,
    quantidade      INTEGER      NOT NULL CHECK (quantidade >= 0),
    preco_unitario  NUMERIC(8,2) NOT NULL,
    CONSTRAINT ck_item_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT uq_item_pedido_produto      UNIQUE (pedido_id, produto_id)
);
CREATE INDEX item_pedido_produto_id_idx ON item_pedido (produto_id);

CREATE TABLE pagamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT        NOT NULL UNIQUE REFERENCES pedido (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    metodo         VARCHAR(12)   NOT NULL,
    status         VARCHAR(10)   NOT NULL DEFAULT 'PENDENTE',
    valor          NUMERIC(10,2) NOT NULL,
    transacao_ref  VARCHAR(64)   NOT NULL,
    pago_em        TIMESTAMPTZ   NULL
);

CREATE TABLE historico_status (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT      NOT NULL REFERENCES pedido (id)  ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    status           VARCHAR(20) NOT NULL,
    alterado_por_id  BIGINT      NULL     REFERENCES usuario (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    alterado_em      TIMESTAMPTZ NOT NULL
);
CREATE INDEX historico_status_pedido_id_idx ON historico_status (pedido_id);

COMMIT;

